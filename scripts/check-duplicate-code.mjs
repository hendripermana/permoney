#!/usr/bin/env node
/**
 * Duplication guard — local mirror of SonarCloud's NEW-code duplication lever.
 *
 * SonarCloud stays authoritative: the quality gate requires duplicated lines on
 * NEW code to stay at or below 3%. That signal only exists *after* CI. This
 * guard runs in `vp run check`, so copy-paste is caught at the developer's
 * keyboard instead of in a pull-request review after the fact. It is a mirror,
 * not a replacement — a pass here never overrides a Sonar finding.
 *
 * WHAT IT DOES
 *   Runs `jscpd` over the application source tree with a committed fingerprint
 *   baseline (`scripts/jscpd-baseline.json`) and fails if the report contains
 *   any clone whose fingerprint is absent from that baseline (or whose
 *   multiplicity exceeds it). The gate allows ZERO new clones. The gate policy
 *   is stricter than SonarCloud's CPD defaults on purpose: SonarCloud permits
 *   up to 3% duplicated lines on new code, this guard permits none.
 *
 *   The printed failure lists EVERY duplicate the report marks `isNew` — not a
 *   "top 10 by size" sample. A new 10-line clone must be named precisely even
 *   when forty larger clones already exist.
 *
 * SCAN SCOPE
 *   - `src/**\/*.{ts,tsx}` only — the shipped app (routes, components, lib,
 *     server functions). `tests/` (integration/e2e) and `scripts/` are out of
 *     scope in v1; they are not part of the app bundle this lever protects.
 *   - `**\/*.gen.ts` is excluded, which covers `src/routeTree.gen.ts`. That file
 *     is generated by TanStack Router on every route change, is not
 *     hand-authored, and would otherwise churn the baseline without anyone
 *     writing duplicate code. (It is also gitignored, and jscpd honors
 *     .gitignore by default; the explicit ignore keeps the intent documented
 *     and independent of that default.)
 *   - Test files that live under `src/` (`src/**\/*.test.ts(x)`) are in scope,
 *     matching SonarCloud, which also counts duplication in test sources.
 *   - The scope lives in ONE place: `scripts/jscpd.config.json`. This shim
 *     validates it strictly, passes `--config <abs path>` (so jscpd's
 *     auto-discovery cannot move the gate) and refuses to run if
 *     `.jscpd.json`, `.config/jscpd.json`, or `package.json#jscpd` exists.
 *   - `"."` is passed as the scan root so the config's relative `pattern` and
 *     the report's relative file names resolve from the repository root
 *     regardless of the caller's cwd. jscpd still honors `.gitignore`.
 *
 * THRESHOLDS
 *   `minTokens: 75`, `minLines: 5`, `mode: "mild"` (pinned in the config and
 *   also passed explicitly). Below that, repeats are usually import lists, JSX
 *   prop shapes, or three-line scaffolding where extraction makes the code
 *   worse. These values keep the baseline small enough that any new clone is
 *   worth a look.
 *
 * BASELINE
 *   `scripts/jscpd-baseline.json` is generated by jscpd 5.4.2's
 *   `--update-baseline` from `scripts/jscpd.config.json`. Fingerprints are
 *   content-based (moving a clone to another file does not make it new) and
 *   carry a multiplicity, so adding a third copy of an already-duplicated
 *   block is still a new clone. This supersedes the old count-only gate: it
 *   cannot be circumvented by removing a clone elsewhere in the tree.
 *
 *   BASELINE_CLONES = 40 and BASELINE_SOURCES = 305 were measured at commit
 *   1f86b13 (main, 2026-10-25) with exactly this config. BASELINE_CLONES is a
 *   cross-check against the baseline's fingerprint multiplicity sum; it is not
 *   a second, independent gate. BASELINE_SOURCES is the scope anchor: the
 *   analyzed source count is printed on every run, and ratchet advice is only
 *   offered when the analyzer saw at least that many sources.
 *
 *   To ratchet after removing real duplication:
 *     node scripts/check-duplicate-code.mjs --update-baseline
 *   then lower BASELINE_CLONES (and update BASELINE_SOURCES when the scope
 *   legitimately grew) in the same reviewed change. Never edit the baseline by
 *   hand and never raise it without reviewer sign-off.
 *
 * FAIL-CLOSED BEHAVIOR
 *   A missing/mismatched jscpd version, a missing config or baseline, a
 *   conflicting auto-config source, a crashed scan, an unreadable/truncated
 *   report, a report with zero analyzed sources, a `duplicates` array that
 *   disagrees with its own `clones` statistic, or an `isNew` tally that
 *   disagrees with `newClones` all exit 1. An empty scan must never look like
 *   "0 clones, pass".
 *
 *   `--fail-on-empty` is defence-in-depth only: the guard independently
 *   rejects a report with `sources <= 0`, so the gate holds even if jscpd's own
 *   flag changes. The report contract checks (`duplicates.length === clones`,
 *   `ΣisNew === newClones`) are same-process consistency checks on ONE report;
 *   they are NOT independent validation of jscpd's detection.
 *
 * USAGE
 *   node scripts/check-duplicate-code.mjs                 # check (default)
 *   node scripts/check-duplicate-code.mjs --update-baseline
 *
 * WIRED IN
 *   `package.json` script `check` (4th guard), which `vp run check` and CI's
 *   `check` job both run. Policy tests live in
 *   `scripts/check-duplicate-code.test.mjs`; the pure decision logic lives in
 *   `scripts/check-duplicate-code.detector.mjs`.
 */

import { execFileSync } from "node:child_process"
import {
  copyFileSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
} from "node:fs"
import { createRequire } from "node:module"
import { tmpdir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import {
  ALLOWED_NEW_CLONES,
  GuardError,
  describeAutoConfigConflict,
  evaluateGuardResult,
  formatNewDuplicates,
  parseBaseline,
  parseReport,
  validateConfig,
} from "./check-duplicate-code.detector.mjs"

// ──────────────────────────────────────────────────────────────────────────
// Policy
// ──────────────────────────────────────────────────────────────────────────
const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url))

/**
 * Fingerprint-multiplicity sum of `scripts/jscpd-baseline.json` at 1f86b13.
 * This is a cross-check, not a second gate: the fingerprint baseline decides
 * pass/fail. Lower it (and regenerate the baseline) when real duplication is
 * removed; never raise it without reviewer sign-off.
 */
const BASELINE_CLONES = 40

/**
 * Analyzed source count at 1f86b13 (main). Scope anchor: printed on every run;
 * ratchet advice is only offered when the current scan saw at least this many
 * sources.
 */
const BASELINE_SOURCES = 305

/** The engine that produced the fingerprints; baseline files are engine-specific. */
const PINNED_JSCPD_VERSION = "5.4.2"

const CONFIG_PATH = join(REPO_ROOT, "scripts", "jscpd.config.json")
const BASELINE_PATH = join(REPO_ROOT, "scripts", "jscpd-baseline.json")
const REPORT_BASENAME = "jscpd-report"
const REPORT_FILENAME = `${REPORT_BASENAME}.json`
const SPAWN_TIMEOUT_MS = 5 * 60 * 1000
const KNOWN_ARGS = new Set(["--update-baseline"])

const UPDATE_BASELINE = process.argv.includes("--update-baseline")

// ──────────────────────────────────────────────────────────────────────────
// Inputs: config, tool, auto-config conflicts
// ──────────────────────────────────────────────────────────────────────────
function loadConfig() {
  let text
  try {
    text = readFileSync(CONFIG_PATH, "utf8")
  } catch (error) {
    throw new GuardError(
      `Cannot read ${CONFIG_PATH}: ${error.code ?? "unknown error"} ${error.message}. ` +
        "The committed config is required so jscpd's auto-discovery cannot move the gate."
    )
  }

  let raw
  try {
    raw = JSON.parse(text)
  } catch (error) {
    throw new GuardError(`${CONFIG_PATH} is not valid JSON: ${error.message}`)
  }

  return validateConfig(raw)
}

function loadRepoPackageJson() {
  const packageJsonPath = join(REPO_ROOT, "package.json")
  try {
    return JSON.parse(readFileSync(packageJsonPath, "utf8"))
  } catch (error) {
    throw new GuardError(
      `Cannot read ${packageJsonPath}: ${error.code ?? "unknown error"} ${error.message}.`
    )
  }
}

function assertNoAutoConfigConflict() {
  const packageJson = loadRepoPackageJson()
  const conflict = describeAutoConfigConflict({
    rootConfig: existsSync(join(REPO_ROOT, ".jscpd.json")),
    nestedConfig: existsSync(join(REPO_ROOT, ".config", "jscpd.json")),
    packageJson: Object.hasOwn(packageJson, "jscpd"),
  })
  if (conflict) {
    throw new GuardError(conflict)
  }
}

/**
 * Resolve jscpd's launcher through Node's module resolver and run it with the
 * current Node binary. This avoids PATH lookups (a caller-controlled PATH
 * could answer for the tool) and keeps working when `node_modules/.bin` is
 * absent, which is common in pnpm layouts.
 */
function resolveJscpd() {
  const require = createRequire(import.meta.url)
  let packageJsonPath
  try {
    packageJsonPath = require.resolve("jscpd/package.json")
  } catch (error) {
    throw new GuardError(
      `jscpd is not installed (${error.code ?? "resolution failed"}). ` +
        `Run \`vp install\`; jscpd is a devDependency pinned to ${PINNED_JSCPD_VERSION}.`
    )
  }

  const packageJson = JSON.parse(readFileSync(packageJsonPath, "utf8"))
  if (packageJson.version !== PINNED_JSCPD_VERSION) {
    throw new GuardError(
      `jscpd ${packageJson.version} is installed, but this guard is pinned to ${PINNED_JSCPD_VERSION}. ` +
        "jscpd changed; deliberately re-measure the baseline before adopting the new engine: " +
        "run `node scripts/check-duplicate-code.mjs --update-baseline`, review the baseline diff, " +
        "and update BASELINE_CLONES/BASELINE_SOURCES here plus the exact pin in package.json."
    )
  }

  const binEntry =
    typeof packageJson.bin === "string"
      ? packageJson.bin
      : packageJson.bin?.jscpd

  if (!binEntry) {
    throw new GuardError(
      `jscpd's package.json (${packageJsonPath}) has no "bin.jscpd" entry; refusing to guess the launcher.`
    )
  }

  return { entry: resolve(dirname(packageJsonPath), binEntry) }
}

// ──────────────────────────────────────────────────────────────────────────
// Scan
// ──────────────────────────────────────────────────────────────────────────
function buildJscpdArgs(jscpdEntry, config, outputDir, baselinePath) {
  const args = [
    jscpdEntry,
    // Positional scan root: keeps config `pattern` and reported file names
    // relative to the repository root, not the caller's cwd.
    ".",
    "--silent",
    "--no-colors",
    "--no-tips",
    // Explicit config: jscpd must never auto-discover policy elsewhere.
    "--config",
    CONFIG_PATH,
    "--mode",
    config.mode,
    "--pattern",
    config.pattern,
    "--format",
    config.format.join(","),
    "--min-tokens",
    String(config.minTokens),
    "--min-lines",
    String(config.minLines),
    "--reporters",
    "json",
    "--report-name",
    REPORT_BASENAME,
    "--output",
    outputDir,
    // Defence-in-depth: the guard also rejects sources <= 0 after parsing.
    "--fail-on-empty",
  ]

  if (config.ignore.length > 0) {
    args.push("--ignore", config.ignore.join(","))
  }

  if (UPDATE_BASELINE) {
    args.push("--baseline", baselinePath, "--update-baseline")
  } else {
    args.push(
      "--baseline",
      baselinePath,
      "--fail-on-new-clones",
      String(ALLOWED_NEW_CLONES)
    )
  }

  return args
}

/**
 * Run jscpd and capture everything needed for an actionable diagnostic. A
 * non-zero status is NOT automatically a tool error: with
 * `--fail-on-new-clones 0`, jscpd exits 1 precisely when the gate should fail,
 * and still writes the report. The caller decides after parsing it.
 */
function runJscpd(jscpdEntry, config, outputDir, baselinePath) {
  const args = buildJscpdArgs(jscpdEntry, config, outputDir, baselinePath)
  try {
    const stdout = execFileSync(process.execPath, args, {
      cwd: REPO_ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      maxBuffer: 16 * 1024 * 1024,
      timeout: SPAWN_TIMEOUT_MS,
    })
    return {
      ok: true,
      status: 0,
      signal: null,
      code: null,
      message: null,
      stdout: stdout.trim(),
      stderr: "",
    }
  } catch (error) {
    return {
      ok: false,
      status: Number.isInteger(error.status) ? error.status : null,
      signal: error.signal ?? null,
      code: error.code ?? null,
      message: error.message ?? null,
      stdout: typeof error.stdout === "string" ? error.stdout.trim() : "",
      stderr: typeof error.stderr === "string" ? error.stderr.trim() : "",
    }
  }
}

function formatScanFailure(scan) {
  const output = [scan.stdout, scan.stderr].filter(Boolean).join("\n")
  const lines = []

  if (/no prebuilt binary for this platform/i.test(output)) {
    lines.push(
      `${PINNED_JSCPD_VERSION} has no prebuilt jscpd binary for this platform.`,
      "Run the gate in CI or on a supported platform (macOS/Linux/Windows, arm64 or x64); do not bypass the guard."
    )
  } else if (/analyzed no files|--fail-on-empty/i.test(output)) {
    lines.push(
      "jscpd analyzed zero source files. Check PATH_PATTERN/FORMATS/IGNORES " +
        "(and scripts/jscpd.config.json) — an empty scan must not pass."
    )
  } else if (/baseline file .* not found/i.test(output)) {
    lines.push(
      `The committed baseline ${BASELINE_PATH} is missing.`,
      "Restore it from git, or regenerate it deliberately with --update-baseline and reviewer sign-off."
    )
  } else {
    lines.push(
      "jscpd failed to run; this is a tool/install error, not a copy-paste verdict."
    )
  }

  lines.push(
    `  exit: ${scan.status ?? "none"} · signal: ${scan.signal ?? "none"} · code: ${scan.code ?? "none"}`
  )
  if (scan.message) {
    lines.push(`  error: ${scan.message}`)
  }
  if (scan.stdout) {
    lines.push(`  stdout: ${scan.stdout}`)
  }
  if (scan.stderr) {
    lines.push(`  stderr: ${scan.stderr}`)
  }

  return lines.join("\n")
}

// ──────────────────────────────────────────────────────────────────────────
// Reporting
// ──────────────────────────────────────────────────────────────────────────
function formatScope(config, sources) {
  const ignoreSuffix =
    config.ignore.length > 0 ? ` · ${config.ignore.join(", ")} excluded` : ""
  return [
    `   ${sources} source file(s) analyzed · baseline ${BASELINE_SOURCES} · jscpd ${PINNED_JSCPD_VERSION} · mode ${config.mode}`,
    `   ${config.pattern} · ≥${config.minTokens} tokens · ≥${config.minLines} lines${ignoreSuffix}`,
  ].join("\n")
}

function formatSourceDrift(sourceDrift) {
  if (!sourceDrift) {
    return null
  }
  if (sourceDrift.direction === "shrank") {
    return `   ⚠️  Source count changed (${sourceDrift.baseline} → ${sourceDrift.current}): re-measure the baseline, do not lower it blindly.`
  }
  return `   ℹ️  Source count grew (${sourceDrift.baseline} → ${sourceDrift.current}): if this is the new floor, update BASELINE_SOURCES in the same reviewed change.`
}

function safeRemove(dir) {
  try {
    rmSync(dir, { recursive: true, force: true })
  } catch (error) {
    console.error(
      `⚠️  Could not remove temp report directory ${dir}: ${error.message}`
    )
  }
}

// ──────────────────────────────────────────────────────────────────────────
// Main
// ──────────────────────────────────────────────────────────────────────────
function main() {
  let outputDir = null
  let keepOutput = false

  try {
    const unknownArgs = process.argv
      .slice(2)
      .filter((arg) => !KNOWN_ARGS.has(arg))
    if (unknownArgs.length > 0) {
      throw new GuardError(
        `Unknown argument(s): ${unknownArgs.join(", ")}. Supported: --update-baseline.`
      )
    }

    const config = loadConfig()
    assertNoAutoConfigConflict()
    const jscpd = resolveJscpd()

    let baseline = null
    let baselineWasUnreadable = false
    if (existsSync(BASELINE_PATH)) {
      if (UPDATE_BASELINE) {
        // The documented recovery from a corrupt baseline is this command.
        // Regenerate from scratch (loudly) instead of dead-ending on the
        // corrupt file; the source-floor check below still guards scope.
        try {
          baseline = parseBaseline(readFileSync(BASELINE_PATH, "utf8"))
        } catch (error) {
          baselineWasUnreadable = true
          console.error(
            `⚠️  Existing baseline is unreadable (${error.message}); regenerating it from the current scan.`
          )
        }
      } else {
        baseline = parseBaseline(readFileSync(BASELINE_PATH, "utf8"))
        if (baseline.cloneCount !== BASELINE_CLONES) {
          throw new GuardError(
            `baseline ${BASELINE_PATH} sums to ${baseline.cloneCount} clone fingerprint(s), ` +
              `but BASELINE_CLONES is ${BASELINE_CLONES}. Update both in the same reviewed change; ` +
              "never edit one without the other."
          )
        }
      }
    } else if (!UPDATE_BASELINE) {
      throw new GuardError(
        `the committed baseline ${BASELINE_PATH} is missing. Restore it, ` +
          "or regenerate it deliberately with --update-baseline and reviewer sign-off."
      )
    }

    outputDir = mkdtempSync(join(tmpdir(), "permoney-jscpd-"))
    const reportPath = join(outputDir, REPORT_FILENAME)

    if (UPDATE_BASELINE) {
      // Write the new baseline to a temp file first. jscpd reads the current
      // baseline (to compute removed fingerprints), then rewrites the temp
      // copy; the committed file is only replaced after the source floor
      // check passes. A partial/bad update can never corrupt the gate.
      const stagedBaselinePath = join(outputDir, "jscpd-baseline.next.json")
      if (baseline) {
        copyFileSync(BASELINE_PATH, stagedBaselinePath)
      }

      const scan = runJscpd(jscpd.entry, config, outputDir, stagedBaselinePath)
      if (!scan.ok || !existsSync(reportPath)) {
        console.error(
          "❌ DUPLICATION BASELINE UPDATE FAILED: jscpd did not complete."
        )
        console.error(formatScanFailure(scan))
        return 1
      }

      let report
      try {
        report = parseReport(readFileSync(reportPath, "utf8"))
      } catch (error) {
        console.error(`❌ DUPLICATION GUARD ERROR: ${error.message}`)
        if (!scan.ok) {
          console.error(formatScanFailure(scan))
        }
        return 1
      }
      if (report.sources < BASELINE_SOURCES) {
        throw new GuardError(
          `refusing to rewrite the baseline from ${report.sources} source file(s); ` +
            `BASELINE_SOURCES is ${BASELINE_SOURCES}. The checkout may be partial, so "duplication dropped" ` +
            "is not a safe conclusion. If the scope shrink is intentional, update BASELINE_SOURCES in the " +
            "same reviewed change first, then re-run --update-baseline."
        )
      }

      const nextBaseline = parseBaseline(
        readFileSync(stagedBaselinePath, "utf8")
      )
      copyFileSync(stagedBaselinePath, BASELINE_PATH)

      console.log(
        `✅ DUPLICATION BASELINE UPDATED: ${nextBaseline.cloneCount} duplicate block(s) in ${report.sources} source file(s) analyzed (baseline ${BASELINE_SOURCES}, jscpd ${PINNED_JSCPD_VERSION}).`
      )
      if (scan.stdout) {
        console.log(scan.stdout)
      }
      if (baselineWasUnreadable) {
        console.log(
          "   ℹ️  The previous baseline was unreadable; every current fingerprint was written fresh. Review the baseline diff carefully."
        )
      }
      if (report.sources > BASELINE_SOURCES) {
        console.log(
          `   ℹ️  Source count grew (${BASELINE_SOURCES} → ${report.sources}): update BASELINE_SOURCES in the same reviewed change.`
        )
      }
      if (nextBaseline.cloneCount < BASELINE_CLONES) {
        console.log(
          `   Lock the win: set BASELINE_CLONES = ${nextBaseline.cloneCount} in scripts/check-duplicate-code.mjs and keep both edits in the same PR.`
        )
      } else if (nextBaseline.cloneCount > BASELINE_CLONES) {
        console.log(
          `   ⚠️  Duplication INCREASED (${BASELINE_CLONES} → ${nextBaseline.cloneCount}). Raising the baseline requires a justification in the PR body and reviewer sign-off; do not commit it silently.`
        )
      } else {
        console.log(
          "   Baseline fingerprints refreshed; BASELINE_CLONES is unchanged."
        )
      }
      return 0
    }

    const scan = runJscpd(jscpd.entry, config, outputDir, BASELINE_PATH)

    if (!existsSync(reportPath)) {
      console.error(
        "❌ DUPLICATION GUARD ERROR: jscpd produced no JSON report."
      )
      console.error(formatScanFailure(scan))
      return 1
    }

    let report
    try {
      report = parseReport(readFileSync(reportPath, "utf8"))
    } catch (error) {
      console.error(`❌ DUPLICATION GUARD ERROR: ${error.message}`)
      if (!scan.ok) {
        console.error(formatScanFailure(scan))
      }
      return 1
    }

    // With --fail-on-new-clones 0 jscpd exits 1 exactly when the fingerprint
    // gate should fail. A non-zero exit with no new clone in the report is a
    // real tool failure and must stay fail-closed.
    if (!scan.ok && report.newCloneCount === 0) {
      console.error(
        "❌ DUPLICATION GUARD ERROR: jscpd exited non-zero without reporting a new clone."
      )
      console.error(formatScanFailure(scan))
      return 1
    }

    const decision = evaluateGuardResult({
      report,
      baselineClones: BASELINE_CLONES,
      baselineSources: BASELINE_SOURCES,
    })
    const scope = formatScope(config, report.sources)
    const drift = formatSourceDrift(decision.sourceDrift)

    if (!decision.ok) {
      keepOutput = true
      if (decision.failure.code === "new-clones") {
        console.error(
          `❌ DUPLICATION GUARD FAILED: ${report.newCloneCount} new duplicate block(s) not in scripts/jscpd-baseline.json ` +
            `(allowed: ${ALLOWED_NEW_CLONES}; ${report.cloneCount} total, BASELINE_CLONES ${BASELINE_CLONES}).`
        )
        console.error(
          "The gate is stricter than SonarCloud's CPD defaults, on purpose: SonarCloud permits up to 3% duplicated lines on new code, this guard permits zero new clone fingerprints."
        )
        console.error("")
        console.error(
          `New duplicate block(s) — every entry the report marks isNew (${decision.newDuplicates.length}):`
        )
        console.error(formatNewDuplicates(decision.newDuplicates))
        console.error("")
        console.error(
          "Fix: extract the shared block into a helper, or make the two sites intentionally different."
        )
        console.error(
          "Accepting this duplication requires a deliberate `node scripts/check-duplicate-code.mjs --update-baseline` refresh plus reviewer sign-off; never edit the baseline by hand."
        )
      } else {
        console.error(
          `❌ DUPLICATION GUARD FAILED: ${report.cloneCount} duplicate block(s) exceed BASELINE_CLONES ${BASELINE_CLONES}, ` +
            "but jscpd reported no new fingerprints."
        )
        console.error(
          "The committed baseline and BASELINE_CLONES disagree (stale or hand-edited). " +
            "Re-measure deliberately with --update-baseline; never hand-edit either side."
        )
      }
      console.error("")
      console.error(scope)
      if (drift) {
        console.error(drift)
      }
      console.error(`Full JSON report kept at: ${reportPath}`)
      return 1
    }

    if (report.cloneCount < BASELINE_CLONES) {
      console.log(
        `✅ DUPLICATION GUARD PASSED: no new clone fingerprints (${report.cloneCount} duplicate block(s), ${BASELINE_CLONES - report.cloneCount} below baseline ${BASELINE_CLONES}).`
      )
    } else {
      console.log(
        `✅ DUPLICATION GUARD PASSED: no new clone fingerprints (${report.cloneCount} duplicate block(s) at baseline ${BASELINE_CLONES}).`
      )
    }
    console.log(scope)
    if (drift) {
      console.log(drift)
    }
    if (decision.ratchet) {
      console.log(
        `   Lock the win: run \`node scripts/check-duplicate-code.mjs --update-baseline\` (drops removed fingerprints) and lower BASELINE_CLONES to ${report.cloneCount} in the same PR.`
      )
    }
    return 0
  } catch (error) {
    console.error(
      `❌ DUPLICATION GUARD ERROR: ${
        error instanceof GuardError
          ? error.message
          : (error.stack ?? error.message)
      }`
    )
    return 1
  } finally {
    if (outputDir && !keepOutput) {
      safeRemove(outputDir)
    }
  }
}

process.exitCode = main()
