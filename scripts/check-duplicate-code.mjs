#!/usr/bin/env node
/**
 * Duplication guard — local mirror of SonarCloud's NEW-code duplication lever.
 *
 * SonarCloud stays authoritative: the quality gate requires duplicated lines on
 * NEW code to stay at or below 3%. That signal only exists *after* CI. This
 * guard runs in `vp run check`, so copy-paste is caught at the developer's
 * keyboard instead of in a pull-request review after the fact. It is a mirror,
 * not a replacement — a pass here never overrides a Sonar finding.
 *
 * WHAT IT DOES
 *   Runs `jscpd` over the application source tree and compares the number of
 *   exact duplicate blocks against BASELINE_CLONES. More clones than the
 *   baseline fails the build; the same or fewer passes.
 *
 * SCAN SCOPE
 *   - `src/**\/*.{ts,tsx}` only — the shipped app (routes, components, lib,
 *     server functions). `tests/` (integration/e2e) and `scripts/` are out of
 *     scope in v1; they are not part of the app bundle this lever protects.
 *   - `**\/*.gen.ts` is excluded, which covers `src/routeTree.gen.ts`. That file
 *     is generated by TanStack Router on every route change, is not
 *     hand-authored, and would otherwise churn the baseline without anyone
 *     writing duplicate code. (It is also gitignored, and jscpd honors
 *     .gitignore by default; the explicit ignore keeps the intent documented
 *     and independent of that default.)
 *   - Test files that live under `src/` (`src/**\/*.test.ts(x)`) are in scope,
 *     matching SonarCloud, which also counts duplication in test sources.
 *
 * THRESHOLDS
 *   `--min-tokens 75 --min-lines 5`. Below that, repeats are usually import
 *   lists, JSX prop shapes, or three-line scaffolding where extraction makes
 *   the code worse. These values keep the baseline small enough that any new
 *   clone is worth a look.
 *
 * BASELINE
 *   BASELINE_CLONES = 40, measured at commit 1f86b13 (main, 2026-10-25) with
 *   exactly the flags in this file. The gate fails when clones > 40.
 *
 *   The baseline is a COUNT, not a fingerprint set, so removing one clone
 *   elsewhere in the tree buys headroom for one new clone. That is the
 *   accepted tradeoff of a zero-config local guard; SonarCloud's new-code
 *   analysis remains the precise, authoritative check. The count only goes
 *   down in normal work: when a PR removes duplication, lower BASELINE_CLONES
 *   in the same PR so the headroom cannot be reused. Raising it requires a
 *   justification in the PR body and reviewer sign-off — a silent baseline
 *   bump defeats the guard.
 *
 * FAIL-CLOSED BEHAVIOR
 *   A missing jscpd install, a crashed scan, a missing/unparseable JSON report,
 *   a report with zero analyzed sources, or a report whose `duplicates` array
 *   disagrees with its own `clones` statistic all exit 1. An empty scan must
 *   never look like "0 clones, pass".
 *
 * USAGE
 *   node scripts/check-duplicate-code.mjs
 *
 * WIRED IN
 *   `package.json` script `check` (4th guard), which `vp run check` and CI's
 *   `check` job both run.
 */

import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, rmSync } from "node:fs"
import { createRequire } from "node:module"
import { tmpdir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

// ──────────────────────────────────────────────────────────────────────────
// Policy
// ──────────────────────────────────────────────────────────────────────────
const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url))

/**
 * Exact duplicate-block count on main @ 1f86b13. Lower it when a PR removes
 * duplication; do not raise it without justification and reviewer sign-off.
 */
const BASELINE_CLONES = 40

const PATH_PATTERN = "src/**/*.{ts,tsx}"
const FORMATS = "typescript,tsx"
const IGNORES = ["**/*.gen.ts"]
const MIN_TOKENS = 75
const MIN_LINES = 5
const MAX_REPORTED_PAIRS = 10
const REPORT_FILENAME = "jscpd-report.json"
const SPAWN_TIMEOUT_MS = 5 * 60 * 1000

// ──────────────────────────────────────────────────────────────────────────
// jscpd discovery
// ──────────────────────────────────────────────────────────────────────────
/**
 * Resolve jscpd's launcher through Node's module resolver and run it with the
 * current Node binary. This avoids PATH lookups (a caller-controlled PATH
 * could answer for the tool) and keeps working when `node_modules/.bin` is
 * absent, which is common in pnpm layouts.
 */
function resolveJscpdEntry() {
  const require = createRequire(import.meta.url)
  let packageJsonPath
  try {
    packageJsonPath = require.resolve("jscpd/package.json")
  } catch {
    throw new Error(
      "jscpd is not installed. Run `vp install` (jscpd is a devDependency in package.json)."
    )
  }

  const packageJson = JSON.parse(readFileSync(packageJsonPath, "utf8"))
  const binEntry =
    typeof packageJson.bin === "string"
      ? packageJson.bin
      : packageJson.bin?.jscpd

  if (!binEntry) {
    throw new Error(
      `jscpd's package.json (${packageJsonPath}) has no "bin.jscpd" entry; refusing to guess the launcher.`
    )
  }

  return resolve(dirname(packageJsonPath), binEntry)
}

// ──────────────────────────────────────────────────────────────────────────
// Scan
// ──────────────────────────────────────────────────────────────────────────
function runJscpd(jscpdEntry, outputDir) {
  // Deliberately no `--threshold` / `--exit-code`: this guard owns the policy
  // (clone count vs. baseline). jscpd must exit 0 on a successful scan even
  // when clones exist, otherwise its non-zero status would be ambiguous with a
  // real tool failure.
  const args = [
    jscpdEntry,
    "--silent",
    "--no-colors",
    "--no-tips",
    "--reporters",
    "json",
    "--report-name",
    "jscpd-report",
    "--output",
    outputDir,
    "--pattern",
    PATH_PATTERN,
    "--format",
    FORMATS,
    "--ignore",
    IGNORES.join(","),
    "--min-tokens",
    String(MIN_TOKENS),
    "--min-lines",
    String(MIN_LINES),
    "--fail-on-empty",
  ]

  try {
    const stdout = execFileSync(process.execPath, args, {
      cwd: REPO_ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      maxBuffer: 16 * 1024 * 1024,
      timeout: SPAWN_TIMEOUT_MS,
    })
    return { ok: true, output: stdout.trim() }
  } catch (error) {
    const captured = [error.stdout, error.stderr]
      .filter((chunk) => typeof chunk === "string" && chunk.trim() !== "")
      .join("\n")
      .trim()
    return { ok: false, output: captured }
  }
}

function loadReport(reportPath) {
  let report
  try {
    report = JSON.parse(readFileSync(reportPath, "utf8"))
  } catch (error) {
    throw new Error(
      `jscpd did not produce a readable JSON report at ${reportPath}: ${error.message}`
    )
  }

  const total = report?.statistics?.total
  if (!total || typeof total.clones !== "number") {
    throw new Error(
      "jscpd's JSON report has no statistics.total.clones; the report contract changed."
    )
  }
  if (typeof total.sources !== "number" || total.sources <= 0) {
    throw new Error(
      "jscpd analyzed zero source files. Check PATH_PATTERN/FORMATS/IGNORES — an empty scan must not pass."
    )
  }
  if (!Array.isArray(report.duplicates)) {
    throw new Error(
      "jscpd's JSON report has no duplicates array; the report contract changed."
    )
  }
  if (report.duplicates.length !== total.clones) {
    throw new Error(
      `jscpd report is inconsistent: statistics.total.clones=${total.clones} but duplicates.length=${report.duplicates.length}. Refusing to compare an unreliable count.`
    )
  }

  return {
    cloneCount: total.clones,
    duplicates: report.duplicates,
    sources: total.sources,
  }
}

// ──────────────────────────────────────────────────────────────────────────
// Reporting
// ──────────────────────────────────────────────────────────────────────────
function formatLocation(file) {
  return `${file.name}:${file.start}-${file.end}`
}

function formatWorstPairs(duplicates) {
  return [...duplicates]
    .sort(
      (a, b) =>
        b.lines - a.lines ||
        b.tokens - a.tokens ||
        a.firstFile.name.localeCompare(b.firstFile.name) ||
        a.firstFile.start - b.firstFile.start
    )
    .slice(0, MAX_REPORTED_PAIRS)
    .map((duplicate, index) => {
      const rank = String(index + 1).padStart(2)
      return [
        `  ${rank}. ${duplicate.lines} lines / ${duplicate.tokens} tokens`,
        `      ${formatLocation(duplicate.firstFile)}  <->  ${formatLocation(duplicate.secondFile)}`,
      ].join("\n")
    })
    .join("\n")
}

// ──────────────────────────────────────────────────────────────────────────
// Main
// ──────────────────────────────────────────────────────────────────────────
function main() {
  let outputDir
  try {
    const jscpdEntry = resolveJscpdEntry()
    outputDir = mkdtempSync(join(tmpdir(), "permoney-jscpd-"))

    const scan = runJscpd(jscpdEntry, outputDir)
    if (!scan.ok) {
      console.error("❌ DUPLICATION GUARD ERROR: jscpd failed to run.")
      if (scan.output !== "") {
        console.error(scan.output)
      }
      console.error(
        "Fix the tool error above (usually a stale install: `vp install`) and re-run."
      )
      return 1
    }

    const { cloneCount, duplicates, sources } = loadReport(
      join(outputDir, REPORT_FILENAME)
    )

    if (cloneCount > BASELINE_CLONES) {
      const delta = cloneCount - BASELINE_CLONES
      console.error(
        `❌ DUPLICATION GUARD FAILED: ${cloneCount} duplicate block(s), baseline is ${BASELINE_CLONES} (+${delta}).`
      )
      console.error(
        "Copy-paste is leaking past the local mirror of SonarCloud's NEW-code duplication lever (≤3%)."
      )
      console.error(
        "Extract the shared block into a helper, or make the two sites intentionally different."
      )
      console.error(
        "Raising BASELINE_CLONES is allowed only with a justification in the PR body and reviewer sign-off."
      )
      console.error("")
      console.error(
        `Worst current duplicate blocks (top ${Math.min(MAX_REPORTED_PAIRS, duplicates.length)}, by lines then tokens):`
      )
      console.error(formatWorstPairs(duplicates))
      return 1
    }

    if (cloneCount < BASELINE_CLONES) {
      console.log(
        `✅ DUPLICATION GUARD PASSED: ${cloneCount} duplicate block(s), ${BASELINE_CLONES - cloneCount} below baseline (${BASELINE_CLONES}).`
      )
      console.log(
        `   Lock the win in: set BASELINE_CLONES = ${cloneCount} in scripts/check-duplicate-code.mjs.`
      )
      return 0
    }

    console.log(
      `✅ DUPLICATION GUARD PASSED: ${cloneCount} duplicate block(s) at baseline (gate fails above ${BASELINE_CLONES}).`
    )
    console.log(
      `   ${sources} source file(s) · ${PATH_PATTERN} · ≥${MIN_TOKENS} tokens · ≥${MIN_LINES} lines · ${IGNORES.join(", ")} excluded`
    )
    return 0
  } catch (error) {
    console.error(`❌ DUPLICATION GUARD ERROR: ${error.message}`)
    return 1
  } finally {
    if (outputDir) {
      rmSync(outputDir, { recursive: true, force: true })
    }
  }
}

process.exitCode = main()
